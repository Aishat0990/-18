#ifndef DIGIT_UTILS_H
#define DIGIT_UTILS_H

// Возвращает true, если в десятичной записи числа n ровно одна цифра 5.
//
// Особенности:
//  - знак числа не учитывается (работаем с модулем числа);
//  - для n == 0 возвращает false (в записи "0" цифры 5 нет);
//  - корректно обрабатывает крайние значения long long,
//    включая LLONG_MIN (для него модуль не помещается в long long,
//    поэтому применяется беззнаковая арифметика).
bool hasExactlyOneFive(long long n);

#endif // DIGIT_UTILS_H
